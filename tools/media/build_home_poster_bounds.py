#!/usr/bin/env python3
"""Build normalized alpha bounds for HipLab posters with no rendered props."""

import argparse
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "assets/public_media/catalog/catalog.json"
POSTERS = ROOT / "assets/public_posters"
OUTPUT = ROOT / "lib/hip/data/hip_home_poster_bounds.dart"

# The catalog describes workout equipment. These images also render a prop.
RENDERED_PROPS = {
    "lats-A",
    "o-stand-sidebend",
    "obliques-A",
    "rotator-cuff-A",
    "serratus-A",
    "triceps-A",
}
# These exercises list a mat, but their bundled poster shows the figure alone.
RENDERED_WITHOUT_PROPS = {
    "h-bear-plank",
    "h-bridge-overhead",
    "h-half-kneeling-quad-stretch",
    "h-inner-thigh",
    "h-mountain-climber",
    "h-pike-pushup",
    "h-supine-cactus-chest",
    "t-flare-side-hold",
    "t-lsit-open-close",
    "t-lsit-tuck",
    "t-lsit-vsit-circles",
    "t-lsit-wide",
    "t-seated-straddle-ext",
    "t-seated-straddle-lifts",
    "t-straddle-hold",
    "t-tuck-planche",
    "t-vsit",
}


def generate():
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    lines = [
        "// Generated by tools/media/build_home_poster_bounds.py.",
        "import 'dart:ui' show Rect;",
        "",
        "const homeContactShadowBounds = <String, Rect>{",
    ]
    for drill in sorted(catalog["drills"], key=lambda drill: drill["id"]):
        name = drill["id"]
        if name in RENDERED_PROPS or (
            drill["equipment"] and name not in RENDERED_WITHOUT_PROPS
        ):
            continue
        standing = POSTERS / f"{name}.webp"
        cover = POSTERS / "r2-v11/cover" / standing.name
        # Use the same poster priority as HipPublicMedia.current.
        path = standing if standing.is_file() else cover
        with Image.open(path) as image:
            if image.mode != "RGBA":
                raise ValueError(f"Expected a transparent poster: {path.name}")
            bounds = image.getchannel("A").getbbox()
            if bounds is None:
                raise ValueError(f"Empty poster: {path.name}")
            width, height = image.size
        coordinates = [
            f"{value / size:.6f}"
            for value, size in zip(bounds, (width, height, width, height))
        ]
        key = path.relative_to(ROOT).as_posix()
        prefix = f"  '{key}': Rect.fromLTRB("
        if len(prefix) > 80:
            lines.extend([f"  '{key}':", f"      Rect.fromLTRB({', '.join(coordinates)}),"])
        else:
            lines.extend([prefix, *(f"    {value}," for value in coordinates), "  ),"])
    return "\n".join([*lines, "};", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check generated bounds")
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit(f"Regenerate {OUTPUT.relative_to(ROOT)}")
    else:
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
